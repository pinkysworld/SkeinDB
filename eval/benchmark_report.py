#!/usr/bin/env python3
"""Reproducible benchmark report generator for SkeinDB.

SkeinDB ships a built-in ``transport-bench`` subcommand that measures SkeinQL
round-trip latency across the HTTP/2, QUIC, and MySQL transports and prints a
JSON report (see ``crates/skeindb/src/transport_bench.rs``). This script turns
that raw JSON into a deterministic, review-friendly Markdown report that also
captures the environment (git commit, rustc version, OS, CPU count) so a run can
be reproduced and compared later.

Two modes:

* Offline / reproducible: render a previously captured report::

      python eval/benchmark_report.py --from-json report.json -o REPORT.md

* Live: build + run the benchmark against a server you started, e.g.::

      target/release/skeindb serve --data ./data &
      target/release/skeindb transport-bench --json > report.json
      python eval/benchmark_report.py --from-json report.json

The pure functions (``summarize_report``, ``render_markdown``, ``format_ns``)
have no I/O and are unit-tested in ``test_benchmark_report.py`` so the report
formatting is validated without a live server.
"""

from __future__ import annotations

import argparse
import json
import os
import platform
import subprocess
import sys
from typing import Any, Dict, List, Optional


def format_ns(nanos: float) -> str:
    """Render a nanosecond duration as a compact, human-readable string."""
    ns = float(nanos)
    if ns < 1_000:
        return f"{ns:.0f} ns"
    if ns < 1_000_000:
        return f"{ns / 1_000:.2f} us"
    if ns < 1_000_000_000:
        return f"{ns / 1_000_000:.2f} ms"
    return f"{ns / 1_000_000_000:.3f} s"


def summarize_report(report: Dict[str, Any]) -> Dict[str, Any]:
    """Extract a normalized, sorted summary from a ``transport-bench`` report.

    The summary is deterministic (transports sorted by name) so two runs of the
    same report always render identically, which keeps diffs meaningful.
    """
    results: List[Dict[str, Any]] = list(report.get("results", []))
    rows: List[Dict[str, Any]] = []
    for run in results:
        latency = run.get("latency", {})
        rows.append(
            {
                "transport": run.get("transport", "?"),
                "request_shape": run.get("request_shape", ""),
                "protocol_version": run.get("protocol_version"),
                "samples": int(run.get("samples", 0)),
                "p50_ns": float(latency.get("p50_ns", 0)),
                "p95_ns": float(latency.get("p95_ns", 0)),
                "p99_ns": float(latency.get("p99_ns", 0)),
                "mean_ns": float(latency.get("mean_ns", 0)),
                "max_ns": float(latency.get("max_ns", 0)),
            }
        )
    rows.sort(key=lambda r: r["transport"])

    fastest_p50 = min(rows, key=lambda r: r["p50_ns"]) if rows else None
    return {
        "sql": report.get("sql", ""),
        "concurrency": int(report.get("concurrency", 0)),
        "requests_per_transport": int(report.get("requests_per_transport", 0)),
        "rows": rows,
        "fastest_transport_by_p50": fastest_p50["transport"] if fastest_p50 else None,
    }


def collect_environment() -> Dict[str, str]:
    """Best-effort, side-channel-free environment metadata for reproducibility."""

    def _run(cmd: List[str]) -> str:
        try:
            out = subprocess.run(cmd, capture_output=True, text=True, timeout=10)
            return out.stdout.strip() or out.stderr.strip()
        except (OSError, subprocess.SubprocessError):
            return "unavailable"

    return {
        "git_commit": _run(["git", "rev-parse", "--short", "HEAD"]),
        "git_dirty": "dirty" if _run(["git", "status", "--porcelain"]) else "clean",
        "rustc": _run(["rustc", "--version"]),
        "os": f"{platform.system()} {platform.release()}",
        "machine": platform.machine(),
        "cpu_count": str(os.cpu_count() or "unknown"),
        "python": platform.python_version(),
    }


def render_markdown(env: Dict[str, str], summary: Dict[str, Any]) -> str:
    """Render the Markdown benchmark report (pure, deterministic)."""
    lines: List[str] = []
    lines.append("# SkeinDB Transport Benchmark Report")
    lines.append("")
    lines.append("Generated by `eval/benchmark_report.py` from a `transport-bench --json` run.")
    lines.append("")
    lines.append("## Environment")
    lines.append("")
    lines.append("| Field | Value |")
    lines.append("| --- | --- |")
    for key in ("git_commit", "git_dirty", "rustc", "os", "machine", "cpu_count", "python"):
        lines.append(f"| {key} | {env.get(key, 'unavailable')} |")
    lines.append("")
    lines.append("## Workload")
    lines.append("")
    lines.append(f"- SQL: `{summary.get('sql', '')}`")
    lines.append(f"- Concurrency: {summary.get('concurrency', 0)}")
    lines.append(f"- Requests per transport: {summary.get('requests_per_transport', 0)}")
    fastest = summary.get("fastest_transport_by_p50")
    if fastest:
        lines.append(f"- Fastest transport by p50: **{fastest}**")
    lines.append("")
    lines.append("## Latency by transport")
    lines.append("")
    lines.append("| Transport | Proto | Samples | p50 | p95 | p99 | mean | max |")
    lines.append("| --- | --- | ---: | ---: | ---: | ---: | ---: | ---: |")
    for row in summary.get("rows", []):
        proto = row.get("protocol_version") or "-"
        lines.append(
            "| {transport} | {proto} | {samples} | {p50} | {p95} | {p99} | {mean} | {max} |".format(
                transport=row["transport"],
                proto=proto,
                samples=row["samples"],
                p50=format_ns(row["p50_ns"]),
                p95=format_ns(row["p95_ns"]),
                p99=format_ns(row["p99_ns"]),
                mean=format_ns(row["mean_ns"]),
                max=format_ns(row["max_ns"]),
            )
        )
    lines.append("")
    lines.append(
        "> Numbers are environment-specific; reproduce on your own hardware and "
        "compare against the same commit for meaningful deltas."
    )
    lines.append("")
    return "\n".join(lines)


def load_report(path: str) -> Dict[str, Any]:
    with open(path, "r", encoding="utf-8") as handle:
        return json.load(handle)


def main(argv: Optional[List[str]] = None) -> int:
    parser = argparse.ArgumentParser(description="Render a reproducible SkeinDB benchmark report.")
    parser.add_argument(
        "--from-json",
        required=True,
        help="Path to a transport-bench --json report to render.",
    )
    parser.add_argument(
        "-o",
        "--output",
        help="Write the Markdown report here instead of stdout.",
    )
    args = parser.parse_args(argv)

    report = load_report(args.from_json)
    summary = summarize_report(report)
    env = collect_environment()
    markdown = render_markdown(env, summary)

    if args.output:
        with open(args.output, "w", encoding="utf-8") as handle:
            handle.write(markdown)
        print(f"wrote {args.output}")
    else:
        sys.stdout.write(markdown)
    return 0


if __name__ == "__main__":  # pragma: no cover
    raise SystemExit(main())
